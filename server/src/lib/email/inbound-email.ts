/**
 * The provider-agnostic shape of an inbound email, and the registry of
 * adapters that produce it.
 *
 * The rest of the system knows only `InboundEmail`. A provider adapter's job
 * is to authenticate a payload and translate it into this shape; everything
 * about Mailgun's field names or SendGrid's lack of a signature stops at the
 * edge of `mailgun.ts` and `sendgrid.ts`. Swapping provider is then a config
 * change, and the ingest service and the tests never mention a vendor.
 */
import { timingSafeEqual } from "node:crypto";
import { parseAddress } from "./address.ts";
import type { EmailProvider } from "../../generated/prisma/enums.ts";
import { env } from "../../env.ts";
import type { InboundAttachment } from "./multipart.ts";

/** Longest subject kept. See the truncation note in `address.ts`. */
export const MAX_SUBJECT_LENGTH = 512;

/** What a message with no Subject header is filed under, so no view sees a null. */
export const NO_SUBJECT = "(no subject)";

export type InboundEmail = {
  /** The RFC 5322 Message-ID, angle brackets stripped. Absent if the mail had none. */
  rfcMessageId?: string;
  from: { email: string; name: string };
  /** The address of ours the mail was delivered to. */
  recipient: string;
  /** Never empty: `NO_SUBJECT` stands in for a missing Subject header. */
  subject: string;
  /** The full plain-text body, quotes and all. */
  body: string;
  /** The provider's own quote-stripped body, when it produces one. */
  strippedBody?: string;
  /** UNTRUSTED sender markup. Stored, never rendered unsanitised. */
  bodyHtml?: string;
  inReplyTo?: string;
  /** The References header's ids, oldest first, brackets stripped. */
  references: string[];
  /** Every header the provider exposed, lowercased keys. */
  headers: Record<string, string>;
  attachments: InboundAttachment[];
  /**
   * The mail is machine-generated - an out-of-office, a bounce, or our own
   * outbound mail arriving back. Stored but not converted, so an autoresponder
   * pointed at the support address cannot open a ticket per reply, and cannot
   * trade replies with us forever once 4.12 starts sending.
   */
  autoReply: boolean;
};

/** What an adapter is given: the raw bytes, plus the HTTP framing around them. */
export type InboundContext = {
  /** The body exactly as it arrived. Mailgun's signature covers these bytes. */
  body: Buffer;
  /** Lowercased header names, as Node gives them. */
  headers: Record<string, string | string[] | undefined>;
  /** The decoded form fields and attachment metadata. */
  fields: Record<string, string>;
  attachments: InboundAttachment[];
};

export interface InboundProvider {
  readonly id: EmailProvider;
  /**
   * Is this payload really from the provider? The webhook has no session - this
   * is the whole of its authentication - so a `false` here is a 401 and nothing
   * is written.
   */
  verify(ctx: InboundContext): boolean;
  /**
   * Translates an authenticated payload. `null` means authentic but unusable -
   * no sender address, in practice - which is stored with an `error` rather
   * than discarded or retried.
   */
  parse(ctx: InboundContext): InboundEmail | null;
}

/**
 * Headers that mark mail as machine-generated, and what counts as a match.
 * Checked by both adapters through `detectAutoReply` below.
 *
 * Twenty lines against two real failures: an out-of-office autoresponder
 * opening a ticket for every message it bounces back, and - once outbound send
 * lands - our own replies and its replies answering each other indefinitely.
 */
export function detectAutoReply(
  headers: Record<string, string>,
  fromEmail: string,
): boolean {
  // RFC 3834's own marker. Any value but `no` means generated by a machine.
  const autoSubmitted = headers["auto-submitted"]?.trim().toLowerCase();
  if (autoSubmitted !== undefined && autoSubmitted !== "" && autoSubmitted !== "no") return true;

  const precedence = headers["precedence"]?.trim().toLowerCase();
  if (precedence === "bulk" || precedence === "auto_reply" || precedence === "junk") return true;

  if (headers["x-autoreply"] !== undefined || headers["x-autorespond"] !== undefined) return true;

  // An empty Return-Path is a bounce: there is no address to reply to, which
  // is exactly what a delivery failure notice says.
  const returnPath = headers["return-path"]?.trim();
  if (returnPath === "<>" || returnPath === "") return true;

  // Our own address. Either our outbound mail has come back, or something is
  // forwarding in a circle; converting it would start the loop.
  if (env.supportEmailAddress && fromEmail === env.supportEmailAddress) return true;

  return false;
}

/**
 * Compares two secrets - a signature digest, a password - without leaking
 * where they first differ. `timingSafeEqual` throws on a length mismatch, so
 * that is checked first; a length difference is not itself a secret, since
 * both providers' credentials are fixed-length or attacker-chosen anyway.
 */
export function constantTimeEquals(a: string, b: string): boolean {
  const left = Buffer.from(a, "utf8");
  const right = Buffer.from(b, "utf8");
  if (left.length !== right.length) return false;
  return timingSafeEqual(left, right);
}

/**
 * Which of our addresses the mail was delivered to, given a To/recipient
 * header that may list several.
 *
 * `SUPPORT_EMAIL_ADDRESS` is what picks ours out of the list. Without that
 * setting the first entry is taken, which is why the setting exists: a mail
 * cc'd to both support and a classmate could otherwise record the classmate's
 * address as the recipient. Shared by both adapters - SendGrid's `to` is
 * always the raw header and so is a list more often than Mailgun's.
 */
export function pickRecipient(raw: string | undefined): string {
  if (!raw) return env.supportEmailAddress ?? "";

  const addresses = raw
    .split(",")
    .map((entry) => parseAddress(entry)?.email)
    .filter((email): email is string => email !== undefined);

  if (addresses.length === 0) return env.supportEmailAddress ?? "";

  const support = env.supportEmailAddress;
  if (support) {
    const ours = addresses.find((email) => email === support);
    if (ours) return ours;
  }
  return addresses[0]!;
}
